export interface TaskSpec<K extends JobSlug, O extends object> {
  slug: K;
  label: string;
  /** Retries per §H.9. A number, or `{ attempts, backoff }`. */
  retries: Retries;
  /** §H.9: a fixed key for sweeps (one at a time), a per-entity key for per-order/payment/session work. */
  concurrency: (args: { input: JobInputs[K]; queue: string }) => string;
  /** Fixed crons (§H.9) — queued by the autoRun tick of `queue`. */
  schedule?: Schedule;
  /** Only for the generated `TypedJobs` types; Payload does not validate input against it. */
  inputSchema?: Field[];
  alert: AlertScope;
  /** Refs for the staff alert (e.g. `{ order: input.orderId }`). */
  alertRefs?: (input: JobInputs[K]) => Record<string, string>;
  run: (args: { input: JobInputs[K]; req: PayloadRequest; job: JobLike }) => Promise<O>;
}

/** The loose shape every task is registered with (`JobsConfig.tasks` takes `TaskConfig<any>[]`). */
type AnyTask = TaskConfig<{ input: object; output: object }>;

/**
 * A Payload task from a spec, with the house rules (see the header). The
 * spec is typed precisely from `JobInputs`; the returned config is the loose
 * form Payload registers (its generics resolve against the generated
 * `TypedJobs`, which cannot be named generically here).
 */
export function defineTask<K extends JobSlug, O extends object>(spec: TaskSpec<K, O>): AnyTask {
  const handler: AnyTask["handler"] = async ({ input, req, job }) => {
    try {
      const output = await spec.run({ input: (input ?? {}) as JobInputs[K], req, job: job as unknown as JobLike });
      return { output };
    } catch (error) {
      lastErrors.set(errorKey((job as unknown as JobLike).id, spec.slug), {
        message: scrubError(error),
        logOnly: Boolean(error && typeof error === "object" && (error as { mpLogOnly?: boolean }).mpLogOnly),
      });
      throw error;
    }
  };
  return {
    slug: spec.slug,
    label: spec.label,
    retries: spec.retries,
    concurrency: ((args: { input: object; queue: string }) => spec.concurrency({ input: args.input as JobInputs[K], queue: args.queue })) as AnyTask["concurrency"],
    ...(spec.schedule ? { schedule: spec.schedule } : {}),
    ...(spec.inputSchema ? { inputSchema: spec.inputSchema } : {}),
    handler,
    onFail: finalFailureAlert(
      spec.slug,
      spec.label,
      spec.retries,
      spec.alert,
      spec.alertRefs ? (input) => spec.alertRefs!(input as JobInputs[K]) : undefined,
    ) as unknown as AnyTask["onFail"],
  };
}

/** The schedule entry for a fixed cron on a queue (§H.9 table). */
export const cron = (expression: string, queue: "default" | "email" = "default"): Schedule => [{ cron: expression, queue }];

/** Sweeps return this shape so the admin's job log shows what happened at a glance. */
export interface SweepOutput {
  [key: string]: unknown;
  failures: Array<{ id: string; error: string }>;
}

/**
 * Per-item error capture for sweeps: an item that fails is logged and
 * listed in the job output, and the sweep carries on with the next one.
 */
export async function eachItem<T>(
  req: PayloadRequest,
  items: readonly T[],
  idOfItem: (item: T) => string,
  fn: (item: T) => Promise<void>,
  failures: SweepOutput["failures"],
): Promise<number> {
  let done = 0;
  for (const item of items) {
    try {
      await fn(item);
      done += 1;
    } catch (error) {
      const message = scrubError(error);
      failures.push({ id: idOfItem(item), error: message });
      req.payload.logger.error({ msg: "jobs: item failed", item: idOfItem(item), error: message });
    }
  }
  return done;
}

/**
 * A sweep that finished with item failures still SUCCEEDS (so one bad row
 * does not turn every minute into a failed job), but staff hear about it,
 * once an hour per task, with the job's own output as the detail.
 */
export async function reportSweepFailures(req: PayloadRequest, slug: JobSlug, label: string, job: JobLike, failures: SweepOutput["failures"]): Promise<void> {
  if (failures.length === 0 || !throttle.take(`${slug}:items`)) return;
  try {
    await notifyStaff(req, "job_failed", {
      task: label,
      taskSlug: slug,
      jobId: String(job.id),
      error: `${failures.length} item(s) failed — first: ${failures[0].error}`,
      items: failures.slice(0, 10),
      links: { admin: await adminLink(req, `collections/payload-jobs/${String(job.id)}`) },
    });
  } catch (error) {
    req.payload.logger.error({ msg: `jobs: could not alert staff about ${slug} item failures`, error: scrubError(error) });
  }
}
