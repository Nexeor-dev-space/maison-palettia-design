import { commitTransaction, initTransaction, killTransaction, type Field, type PayloadRequest, type TaskConfig, type WorkflowConfig } from "payload";

import { getPaymentGateway, notifyStaff, publicUrl, type JobInputs, type Mode, type PaymentGateway } from "@/cms/lib/contracts";

import { AlertThrottle, isFinalFailure, scrubError } from "./logic";

/**
 * ==========================================================================
 * What every background job shares — plumbing for cms/jobs/tasks/* (§H.9)
 * ==========================================================================
 *
 * Four pieces, each small:
 *
 *   · `defineTask` — turns a task spec into a Payload `TaskConfig` with the
 *     house rules attached: typed input from `JobInputs` (cms/lib/contracts),
 *     a concurrency key, retries, and the final-failure alert. Every task in
 *     this folder is written with it, so the rules cannot be forgotten on one.
 *   · the final-failure alert — Payload calls `onFail` on EVERY failure,
 *     retries included; `isFinalFailure` (logic.ts) decides which one is the
 *     last, and only that one emails staff (`notifyStaff("job_failed")`),
 *     throttled so an SMTP outage is one email an hour, not hundreds. A
 *     failure that is itself a staff email only logs (it could not be
 *     delivered anyway, and must not loop).
 *   · `enqueue` — queues a task or workflow by its `JobInputs` name, on the
 *     right queue (emails on `email`), without depending on the generated
 *     `TypedJobs` (payload-types.ts is regenerated by 3A-1 after this lands).
 *   · `runSql` / `inTransaction` — raw statements through drizzle's `sql`
 *     tag only (values are bind parameters, never concatenated), joined to
 *     the transaction on `req` when there is one.
 *
 * WHO CALLS WHAT. Jobs reach other agents' code (orders, gateway, email,
 * tickets) only through `@/cms/lib/contracts`; the SQL here touches only
 * rows the jobs own the timing of (holds, claims, stamps). Enum values in
 * SQL are written as literals in the template, never as parameters:
 * Postgres will not compare an enum column with a text parameter.
 */

export type JobSlug = keyof JobInputs;

type Retries = TaskConfig["retries"];
type Schedule = NonNullable<TaskConfig["schedule"]>;
export type JobLike = { id: string | number; totalTried?: number | null; workflowSlug?: string | null; concurrencyKey?: string | null };

/* ────────────────────────────────────────────────────────────────────────── */
/* Queues                                                                     */
/* ────────────────────────────────────────────────────────────────────────── */

/** `email` is polled every 20 s (a customer is waiting for a ticket); everything else every minute. */
export const QUEUE_OF: Partial<Record<JobSlug, "email" | "default">> = {
  "send-email": "email",
  "send-daily-digest": "email",
};

export const WORKFLOW_SLUGS: ReadonlySet<JobSlug> = new Set<JobSlug>(["finalize-order"]);

/**
 * Queues a job by name. Returns the job id, or null when the slug is not
 * registered in this build (so a caller running before a deploy that adds
 * the task degrades to "not queued" instead of an enum violation that
 * would abort its transaction).
 */
export async function enqueue<K extends JobSlug>(req: PayloadRequest, slug: K, input: JobInputs[K], opts: { waitUntil?: Date } = {}): Promise<string | null> {
  const isWorkflow = WORKFLOW_SLUGS.has(slug);
  const jobs = req.payload.config.jobs as { tasks?: Array<{ slug: string }>; workflows?: Array<{ slug: string }> } | undefined;
  const registered = (isWorkflow ? jobs?.workflows : jobs?.tasks)?.some((entry) => entry.slug === slug) ?? false;
  if (!registered) {
    req.payload.logger.warn(`jobs: "${slug}" is not registered in this build; not queued`);
    return null;
  }
  // Cast: `payload.jobs.queue` is typed from the generated `TypedJobs`, which only
  // knows these slugs after `generate:types`; `JobInputs` is the source of truth.
  const queue = req.payload.jobs.queue as unknown as (args: Record<string, unknown>) => Promise<{ id: string | number }>;
  const job = await queue({
    ...(isWorkflow ? { workflow: slug } : { task: slug }),
    input,
    queue: QUEUE_OF[slug] ?? "default",
    req,
    ...(opts.waitUntil ? { waitUntil: opts.waitUntil } : {}),
  });
  return job?.id !== undefined ? String(job.id) : null;
}

