/** A settings global as the server sees it (no access checks; secrets stay masked). */
export async function readSettings<T extends Record<string, unknown>>(req: PayloadRequest, slug: string): Promise<Partial<T>> {
  try {
    // Deliberately no `req` and no `context`: Payload merges a call's context
    // into the request it is given, and a flag such as `internalRead` left on
    // the job's request would reveal secrets to every later read in the job.
    const doc = await req.payload.findGlobal({ slug: slug as never, depth: 0, overrideAccess: true });
    return (doc ?? {}) as Partial<T>;
  } catch (error) {
    req.payload.logger.warn(`jobs: could not read ${slug}: ${scrubError(error)}`);
    return {};
  }
}

/** Absolute admin link for staff emails, e.g. adminLink(req, "collections/orders/abc"). */
export async function adminLink(req: PayloadRequest, path: string): Promise<string> {
  const base = (await publicUrl(req).catch(() => "")) || "";
  return `${base}/admin/${path.replace(/^\/+/, "")}`;
}

/**
 * The gateway that can act on a row minted in `mode`, or null. A row is only
 * ever handled by the gateway of its own mode (§H.5 step 7: a sandbox event
 * can never touch a live order, or the reverse): test/live rows ask for that
 * mode explicitly; mock rows use the default gateway, which is the mock
 * only while Payments is in Mock mode (or has no key) outside production.
 */
export async function gatewayFor(req: PayloadRequest, mode: Mode | null | undefined): Promise<PaymentGateway | null> {
  if (mode !== "test" && mode !== "live" && mode !== "mock") return null;
  const gateway = mode === "mock" ? await getPaymentGateway(req) : await getPaymentGateway(req, { forceMode: mode });
  if (!gateway.isConfigured || gateway.mode !== mode) return null;
  return gateway;
}

/** Duck-typed `MamoApiError` (status + messages), so the check survives a re-export or a second copy of the class. */
export function mamoErrorStatus(error: unknown): number | undefined {
  if (!error || typeof error !== "object") return undefined;
  const e = error as { status?: unknown; messages?: unknown };
  return typeof e.status === "number" && Array.isArray(e.messages) ? e.status : undefined;
}

/** A relationship value (id or populated doc) as an id string. */
export function idOf(value: unknown): string | null {
  if (value === null || value === undefined || value === "") return null;
  if (typeof value === "string" || typeof value === "number") return String(value);
  if (typeof value === "object" && "id" in (value as Record<string, unknown>)) return idOf((value as { id: unknown }).id);
  return null;
}

