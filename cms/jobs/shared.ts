/* Failure handling                                                           */
/* ────────────────────────────────────────────────────────────────────────── */

/**
 * The error a handler threw, by job + task, so `onFail` (which Payload calls
 * without the error) can put the reason in the staff email. Entries are
 * consumed by the next `onFail` for the same job and task.
 */
const lastErrors = new Map<string, { message: string; logOnly: boolean }>();
const errorKey = (jobId: string | number, slug: string) => `${String(jobId)}:${slug}`;

/** Marks an error as "log, do not email staff" — for failures that ARE staff emails. */
export function logOnly<E>(error: E): E {
  if (error && typeof error === "object") (error as { mpLogOnly?: boolean }).mpLogOnly = true;
  return error;
}

const throttle = new AlertThrottle(60 * 60_000);

/** Alert-key granularity: per job for money paths, per task for high-volume or periodic ones. */
export type AlertScope = "job" | "task" | "never";

export const attemptsOf = (retries: Retries | WorkflowConfig["retries"]): number | undefined => {
  if (retries === undefined || retries === null) return undefined;
  if (typeof retries === "number") return retries;
  return typeof retries.attempts === "number" ? retries.attempts : undefined;
};

/**
 * The final-failure alert itself: log it and, unless the scope is "never"
 * or the error was marked `logOnly`, email staff through
 * `notifyStaff("job_failed")`, at most once an hour per key. Best-effort: if
 * the alert cannot be sent, the job row in the admin (System → Background
 * jobs, with Retry) still shows the failure.
 */
export async function alertFinalFailure(args: {
  req: PayloadRequest;
  job: JobLike;
  slug: string;
  label: string;
  message: string;
  logOnly?: boolean;
  scope: AlertScope;
  refs?: Record<string, string>;
}): Promise<void> {
  const { req, job, slug } = args;
  req.payload.logger.error({ msg: `jobs: ${slug} failed for the last time`, jobId: String(job.id), taskSlug: slug, error: args.message });
  if (args.scope === "never" || args.logOnly) return;
  const key = args.scope === "job" ? `${slug}:${String(job.id)}` : slug;
  if (!throttle.take(key)) return;
  try {
    await notifyStaff(
      req,
      "job_failed",
      {
        task: args.label,
        taskSlug: slug,
        jobId: String(job.id),
        attempts: (job.totalTried ?? 0) + 1,
        error: args.message,
        links: { admin: await adminLink(req, `collections/payload-jobs/${String(job.id)}`) },
      },
      args.refs ?? {},
    );
  } catch (error) {
    req.payload.logger.error({ msg: `jobs: could not alert staff about ${slug}`, jobId: String(job.id), error: scrubError(error) });
  }
}

/** The attempts a workflow allows (its `retries`), for tasks that inherit them. */
export function workflowAttempts(req: PayloadRequest, job: JobLike): number | undefined {
  const workflowSlug = job.workflowSlug ?? undefined;
  const workflow = workflowSlug ? req.payload.config.jobs?.workflows?.find((w) => w.slug === workflowSlug) : undefined;
  return attemptsOf(workflow?.retries);
}

/**
 * `onFail` for a task. Payload calls it on EVERY failure (and without the
 * error), so it reads the message the handler stashed and alerts only when
 * `isFinalFailure` says this was the last attempt.
 */
function finalFailureAlert(slug: string, label: string, retries: Retries, scope: AlertScope, refsOf?: (input: Record<string, unknown>) => Record<string, string>) {
  return async ({ input, job, req, taskStatus }: { input?: object; job: JobLike; req: PayloadRequest; taskStatus: { totalTried?: number } | null }) => {
    const stashed = lastErrors.get(errorKey(job.id, slug));
    lastErrors.delete(errorKey(job.id, slug));
    const final = isFinalFailure({
      taskAttempts: attemptsOf(retries),
      workflowAttempts: workflowAttempts(req, job),
      taskTriedBefore: taskStatus?.totalTried ?? 0,
      jobTriedBefore: job.totalTried ?? 0,
      inWorkflow: Boolean(job.workflowSlug),
    });
    if (!final) return;
    await alertFinalFailure({
      req,
      job,
      slug,
      label,
      message: stashed?.message ?? "The task failed (no message).",
      logOnly: stashed?.logOnly,
      scope,
      refs: refsOf?.((input ?? {}) as Record<string, unknown>),
    });
  };
}

