/* SQL                                                                        */
/* ────────────────────────────────────────────────────────────────────────── */

type Executor = { execute: (query: SQL) => Promise<unknown> };
type AdapterLike = {
  drizzle: Executor;
  sessions?: Record<string, { db: Executor } | undefined>;
  execute: (args: { db?: Executor; drizzle?: Executor; sql: SQL }) => Promise<unknown>;
};

/** The drizzle handle of the transaction on `req`, or the pool when there is none. */
async function txDb(req: PayloadRequest): Promise<Executor> {
  const adapter = req.payload.db as unknown as AdapterLike;
  const id = req.transactionID ? await req.transactionID : undefined;
  return (id !== undefined && adapter.sessions?.[String(id)]?.db) || adapter.drizzle;
}

/** One statement, inside `req`'s transaction when there is one; returns the rows. */
export async function runSql<Row extends Record<string, unknown> = Record<string, unknown>>(req: PayloadRequest, query: SQL): Promise<Row[]> {
  const adapter = req.payload.db as unknown as AdapterLike;
  const result = (await adapter.execute({ db: await txDb(req), sql: query })) as { rows?: Row[] } | Row[] | undefined;
  if (Array.isArray(result)) return result;
  return result?.rows ?? [];
}

/**
 * Runs `fn` in a transaction on `req`: joins one the caller already opened,
 * otherwise opens one, commits on success and rolls back on any throw. Each
 * item a sweep handles gets its own, so one bad row never undoes the rest.
 */
export async function inTransaction<T>(req: PayloadRequest, fn: () => Promise<T>): Promise<T> {
  const owner = await initTransaction(req);
  try {
    const result = await fn();
    if (owner) await commitTransaction(req);
    return result;
  } catch (error) {
    if (owner) await killTransaction(req);
    throw error;
  }
}

