#!/usr/bin/env node
/**
 * Blurred stand-ins for the photographs that live in the repo, not the CMS.
 *
 *   node scripts/generate-image-blurs.mjs
 *
 * Some pictures are held in code under public/images/ (the activities' own
 * photographs, the private-event plates) rather than uploaded, so there is no
 * media document to carry their `blurDataURL`. This makes the same 16px WebP
 * stand-in for each (see cms/lib/blurPlaceholder.ts) and writes them to
 * lib/staticBlurs.generated.ts, keyed by public path.
 *
 * Run it after adding or replacing a photograph under public/images/. It is
 * not part of the build on purpose: the output is small, reviewable and
 * committed, and a build that decodes eighty photographs would be slower for
 * no change.
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = path.join(ROOT, "public");
const OUT = path.join(ROOT, "lib", "staticBlurs.generated.ts");

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(jpe?g|png|webp)$/i.test(entry.name)) yield full;
  }
}

const rows = [];
let transparent = 0;
for await (const file of walk(path.join(PUBLIC, "images"))) {
  const image = sharp(file, { failOn: "none" });
  const [{ isOpaque }, meta] = await Promise.all([image.clone().stats(), image.clone().metadata()]);
  if (!isOpaque || !meta.width || !meta.height) {
    transparent++;
    continue;
  }
  const tiny = await image.resize(16, 16, { fit: "inside" }).webp({ quality: 50 }).toBuffer();
  const key = "/" + path.relative(PUBLIC, file).split(path.sep).join("/");
  rows.push([key, `data:image/webp;base64,${tiny.toString("base64")}`, Math.round((meta.width / meta.height) * 10000) / 10000]);
}
rows.sort(([a], [b]) => a.localeCompare(b));

const body = rows.map(([key, src, aspect]) => `  ${JSON.stringify(key)}: { src: ${JSON.stringify(src)}, aspect: ${aspect} },`).join("\n");
await writeFile(
  OUT,
  `/* Generated by scripts/generate-image-blurs.mjs — do not edit by hand. */\n` +
    `/* Blurred stand-ins for the opaque photographs under public/images/, keyed by public path. */\n` +
    `import type { ImageBlur } from "@/types";\n\n` +
    `export const STATIC_BLURS: Record<string, ImageBlur> = {\n${body}\n};\n`,
);
console.log(`generate-image-blurs: ${rows.length} stand-ins written to ${path.relative(ROOT, OUT)}, ${transparent} transparent skipped.`);
